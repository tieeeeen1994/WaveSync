using System.Runtime.InteropServices;

namespace WaveSync.Audio;

// Hand-written Core Audio COM interop, so the project needs no NuGet packages.
// Vtable order matters: methods must be declared in exactly the order the native interfaces define them.

public enum EDataFlow
{
    Render = 0,
    Capture = 1,
    All = 2,
}

public enum ERole
{
    Console = 0,
    Multimedia = 1,
    Communications = 2,
}

[StructLayout(LayoutKind.Sequential)]
public struct PropertyKey
{
    public Guid FormatId;
    public int PropertyId;

    public PropertyKey(Guid formatId, int propertyId)
    {
        FormatId = formatId;
        PropertyId = propertyId;
    }
}

/// <summary>Only the parts of PROPVARIANT we read (VT_LPWSTR strings). Sized for x64.</summary>
[StructLayout(LayoutKind.Explicit, Size = 24)]
public struct PropVariant
{
    [FieldOffset(0)] public ushort VarType;
    [FieldOffset(8)] public IntPtr Pointer;
}

